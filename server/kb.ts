/**
 * 子串扫描同义词扩展 —— 对每条 KB 命中加 +1 分（与原 token 打分叠加，不替换）。
 * 传入原 query 与 tokens，返回"扩展词 - 原 token 自身"集合，避免重复加分。
 */
import { expandQueryBySubstring } from './synonyms.js';
function synonymBonusTerms(query: string, tokens: string[]): string[] {
  const expanded = expandQueryBySubstring(query);
  const tokenSet = new Set(tokens.map(t => t.toLowerCase()));
  // 只保留扩展词里"非原 token"的部分作为加分维度
  return expanded.filter(w => !tokenSet.has(w.toLowerCase()));
}

/**
 * 基于关键词命中打分（BM25 简化版），返回 topN 条目。
 * 评分规则：
 *  - 关键词（kw[]）每命中 +2 分
 *  - 问题（q）包含查询词 +1 分
 *  - 专业表述（pro）/平易表述（easy）包含 +0.5 分
 *  - 引用规范号（cite）包含 +0.5 分
 *  - 子串同义词扩展词命中 kw/pro/easy/clause 每条 +1 分（叠加层）
 */
export function lookupKB(query: string, topK: number = 3): KBEntry[] {
  if (!query || !query.trim()) return [];

  // 分词：中文按字符 + 英文/数字按词
  const tokens: string[] = [];
  const q = query.toLowerCase();
  // 中文连续串拆分（每字符一个 token）
  const cnRegex = /[一-龥]+/g;
  let m: RegExpExecArray | null;
  while ((m = cnRegex.exec(query)) !== null) {
    for (const ch of m[0]) tokens.push(ch);
  }
  // 英文/数字词
  const enRegex = /[a-z0-9]+/gi;
  while ((m = enRegex.exec(query)) !== null) tokens.push(m[0].toLowerCase());
  // 也支持整词（如 GB16889、kPa）
  const wholeRegex = /[A-Z]+[\w./-]*|\d+[a-zA-Z%]+|[a-z]+_\w+/g;
  while ((m = wholeRegex.exec(query)) !== null) tokens.push(m[0].toLowerCase());

  if (tokens.length === 0) return [];

  // 同义词扩展词（去掉与原 token 重叠的部分）
  const synTerms = synonymBonusTerms(query, tokens);

  const scored = KB_ENTRIES.map(entry => {
    let score = 0;
    const kwLower = entry.kw.map(k => k.toLowerCase());
    const proLower = entry.pro.toLowerCase();
    const easyLower = entry.easy.toLowerCase();
    const citeLower = entry.cite.toLowerCase();
    const qLower = entry.q.toLowerCase();
    const clauseLower = (entry.clause || '').toLowerCase();

    for (const t of tokens) {
      if (!t) continue;
      // 关键词命中（强）
      if (kwLower.some(k => k.includes(t) || t.includes(k))) score += 2;
      // 问题命中
      if (qLower.includes(t)) score += 1;
      // 专业/平易表述命中
      if (proLower.includes(t)) score += 0.5;
      if (easyLower.includes(t)) score += 0.5;
      // 规范引用命中
      if (citeLower.includes(t)) score += 0.5;
    }
    // 同义词扩展词命中 —— 叠加层（每命中 1 个 +1 分）
    for (const s of synTerms) {
      const sl = s.toLowerCase();
      if (!sl) continue;
      if (kwLower.some(k => k.includes(sl) || sl.includes(k))) score += 1;
      if (proLower.includes(sl)) score += 1;
      if (easyLower.includes(sl)) score += 1;
      if (clauseLower.includes(sl)) score += 1;
    }
    return { entry, score };
  });

  return scored
    .filter(s => s.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, topK)
    .map(s => s.entry);
}

/** 返回全部条目的关键词打分（供混合检索组合向量分使用） */
export function scoreKB(query: string): { entry: KBEntry; score: number }[] {
  if (!query || !query.trim()) return KB_ENTRIES.map(entry => ({ entry, score: 0 }));
  const tokens: string[] = [];
  const cnRegex = /[一-龥]+/g; let m: RegExpExecArray | null;
  while ((m = cnRegex.exec(query)) !== null) for (const ch of m[0]) tokens.push(ch);
  const enRegex = /[a-z0-9]+/gi;
  while ((m = enRegex.exec(query)) !== null) tokens.push(m[0].toLowerCase());
  const wholeRegex = /[A-Z]+[\w./-]*|\d+[a-zA-Z%]+|[a-z]+_\w+/g;
  while ((m = wholeRegex.exec(query)) !== null) tokens.push(m[0].toLowerCase());
  if (tokens.length === 0) return KB_ENTRIES.map(entry => ({ entry, score: 0 }));

  // 同义词扩展词
  const synTerms = synonymBonusTerms(query, tokens);

  return KB_ENTRIES.map(entry => {
    let score = 0;
    const kwLower = entry.kw.map(k => k.toLowerCase());
    const qLower = entry.q.toLowerCase();
    const proLower = entry.pro.toLowerCase();
    const easyLower = entry.easy.toLowerCase();
    const citeLower = entry.cite.toLowerCase();
    const clauseLower = (entry.clause || '').toLowerCase();
    for (const t of tokens) {
      if (kwLower.some(k => k.includes(t) || t.includes(k))) score += 2;
      if (qLower.includes(t)) score += 1;
      if (proLower.includes(t)) score += 0.5;
      if (easyLower.includes(t)) score += 0.5;
      if (citeLower.includes(t)) score += 0.5;
    }
    // 同义词扩展词命中 —— 叠加层（每命中 1 个 +1 分）
    for (const s of synTerms) {
      const sl = s.toLowerCase();
      if (!sl) continue;
      if (kwLower.some(k => k.includes(sl) || sl.includes(k))) score += 1;
      if (proLower.includes(sl)) score += 1;
      if (easyLower.includes(sl)) score += 1;
      if (clauseLower.includes(sl)) score += 1;
    }
    return { entry, score };
  });
}

